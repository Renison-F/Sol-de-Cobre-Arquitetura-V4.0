#!/usr/bin/env python3
"""Run the installed Unity Editor. Does not install, license or synthesize Unity."""
import argparse, json, subprocess, sys
from pathlib import Path

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--editor',type=Path,required=True)
    parser.add_argument('--project',type=Path,required=True)
    parser.add_argument('--task',choices=['lab','editmode','lab-android'],required=True)
    parser.add_argument('--dry-run',action='store_true')
    args=parser.parse_args()
    editor=args.editor.resolve();project=args.project.resolve()
    version_file=project/'ProjectSettings/ProjectVersion.txt'
    if not editor.is_file() or not version_file.is_file() or not (project/'Assets').is_dir():
        parser.error('Provide a real Editor binary and a real Unity project generated by the Editor.')
    if '6000.3.24f1' not in version_file.read_text(encoding='utf-8'):
        parser.error('Editor project baseline differs from 6000.3.24f1. Homologate the version and update this runner/ADR together.')
    logs=project/'Builds/Logs'
    command=[str(editor),'-batchmode','-projectPath',str(project),'-logFile',str(logs/(args.task+'.log'))]
    if args.task=='editmode':
        command+=['-runTests','-testPlatform','EditMode','-testResults',str(logs/'editmode-results.xml')]
    else:
        command+=['-quit']
        if args.task=='lab-android':command+=['-buildTarget','Android']
        method='CreateLab' if args.task=='lab' else 'BuildLabAndroid'
        command+=['-executeMethod','SolDeCobre.EditorTools.ProjectBootstrap.'+method]
    print(json.dumps({'command':command,'dry_run':args.dry_run},ensure_ascii=False))
    if args.dry_run:return 0
    logs.mkdir(parents=True,exist_ok=True)
    try:return subprocess.run(command,check=False).returncode
    except OSError as exc:print(str(exc),file=sys.stderr);return 1
if __name__=='__main__':sys.exit(main())
